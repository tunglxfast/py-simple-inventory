    def __init__(self) -> None:
        self.language = "vi"

    def set_language(self, language: str) -> None:
        if language in TRANSLATIONS:
            self.language = language

    def t(self, key: str) -> str:
        return TRANSLATIONS[self.language].get(key, key)
